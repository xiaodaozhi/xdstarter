# scripts/generate_pinyin_data.py

"""Reproduce the vendored Unihan subset offline; never downloads data."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import unicodedata
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "third_party/unicode"
MANIFEST = DATA_DIR / "manifest.json"
VERSION = "17.0.0"
ARCHIVE_SHA256 = "f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e"
PROPERTIES = ("kMandarin", "kTGHZ2013", "kXHC1983", "kHanyuPinyin")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def normalize_reading(reading: str) -> str:
    # Preserve the distinction between u and u-diaeresis before stripping tones.
    reading = unicodedata.normalize("NFC", reading).translate(
        str.maketrans({character: "v" for character in "üǖǘǚǜ"})
    )
    normalized = "".join(
        character
        for character in unicodedata.normalize("NFD", reading)
        if not unicodedata.combining(character)
    )
    if not re.fullmatch(r"[a-z]{1,16}", normalized):
        raise ValueError(f"Unsupported Mandarin reading: {reading!r}")
    return normalized


def table_from_archive(archive_path: Path) -> bytes:
    archive = archive_path.read_bytes()
    if sha256(archive) != ARCHIVE_SHA256:
        raise ValueError("Source archive SHA256 differs from fixed Unihan 17.0.0")
    fields: dict[int, dict[str, str]] = {}
    with ZipFile(archive_path) as source:
        # UAX 38 warns that property file placement may change. Select by property.
        for name in sorted(source.namelist()):
            if not re.fullmatch(r"Unihan_[A-Za-z]+\.txt", name):
                continue
            for line in source.read(name).decode("utf-8").splitlines():
                if not line or line.startswith("#"):
                    continue
                scalar, property_name, value = line.split("\t")
                if property_name not in PROPERTIES:
                    continue
                codepoint = int(scalar.removeprefix("U+"), 16)
                properties = fields.setdefault(codepoint, {})
                if property_name in properties:
                    raise ValueError(f"Duplicate property at {scalar}: {property_name}")
                properties[property_name] = value
    records = []
    for codepoint, properties in sorted(fields.items()):
        readings = []
        for property_name in PROPERTIES:
            for group in properties.get(property_name, "").split():
                value = group if property_name == "kMandarin" else group.split(":", 1)[1]
                readings.extend(normalize_reading(reading) for reading in value.split(","))
        unique = list(dict.fromkeys(readings))
        records.append(f"{codepoint:X}\t{','.join(unique)}\n")
    return "".join(records).encode("ascii")


def parse_table(table: bytes) -> list[tuple[int, list[str]]]:
    if b"\r" in table or not table.endswith(b"\n"):
        raise ValueError("Canonical TSV requires LF line endings and a final newline")
    records = []
    previous = -1
    for line in table.decode("ascii").splitlines():
        scalar, value = line.split("\t")
        codepoint = int(scalar, 16)
        if scalar != f"{codepoint:X}" or codepoint <= previous:
            raise ValueError("Canonical TSV requires unique increasing uppercase code points")
        if not 0 <= codepoint <= 0x10FFFF or 0xD800 <= codepoint <= 0xDFFF:
            raise ValueError("Invalid Unicode scalar in canonical TSV")
        readings = value.split(",")
        if not 1 <= len(readings) <= 32 or len(set(readings)) != len(readings):
            raise ValueError(f"Invalid or duplicate readings at {scalar}")
        if any(not re.fullmatch(r"[a-z]{1,16}", reading) for reading in readings):
            raise ValueError(f"Invalid normalized reading at {scalar}")
        records.append((codepoint, readings))
        previous = codepoint
    return records


def render_cpp(records: list[tuple[int, list[str]]]) -> bytes:
    lines = [
        "// third_party/unicode/unihan_pinyin.inc",
        "",
        "// Generated by scripts/generate_pinyin_data.py; do not edit.",
        "// Derived from Unicode Unihan 17.0.0, Copyright 2025 Unicode, Inc.",
        "// Unicode License v3: see third_party/unicode/LICENSE.txt and README.md.",
    ]
    # One small string per record avoids MSVC's concatenated string literal limit.
    lines.extend(f'{{0x{codepoint:X}U, "{",".join(readings)}"}},' for codepoint, readings in records)
    return ("\n".join(lines) + "\n").encode("ascii")


def table_stats(records: list[tuple[int, list[str]]]) -> dict[str, int]:
    return {
        "codepoints": len(records),
        "readings": sum(len(readings) for _, readings in records),
        "polyphonicCodepoints": sum(len(readings) > 1 for _, readings in records),
        "maxReadingsPerCodepoint": max(len(readings) for _, readings in records),
        "maxReadingLength": max(len(reading) for _, readings in records for reading in readings),
    }


def verify_or_write(path: Path, data: bytes, expected: dict, check: bool) -> None:
    if sha256(data) != expected["sha256"] or len(data) != expected["bytes"]:
        raise ValueError(f"Generated content differs from the manifest: {path.relative_to(ROOT)}")
    if check:
        if not path.exists() or path.read_bytes() != data:
            raise ValueError(f"Stale generated file: {path.relative_to(ROOT)}")
    else:
        path.write_bytes(data)


def run(source_zip: Path | None = None, check: bool = False) -> dict[str, int]:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if (
        manifest["schemaVersion"] != 1
        or manifest["source"]["version"] != VERSION
        or manifest["source"]["archiveSha256"] != ARCHIVE_SHA256
        or manifest["extraction"]["propertiesInPreferenceOrder"] != list(PROPERTIES)
    ):
        raise ValueError("Manifest and generator source contract differ")
    outputs = manifest["outputs"]
    table_path = DATA_DIR / "unihan_pinyin.tsv"
    cpp_path = DATA_DIR / "unihan_pinyin.inc"
    table = table_from_archive(source_zip) if source_zip else table_path.read_bytes()
    records = parse_table(table)
    stats = table_stats(records)
    if stats != manifest["statistics"]:
        raise ValueError("Canonical table statistics differ from the manifest")
    license_data = (DATA_DIR / "LICENSE.txt").read_bytes()
    if sha256(license_data) != manifest["license"]["sha256"]:
        raise ValueError("Vendored Unicode license differs from the recorded notice")
    if b"UNICODE LICENSE V3" not in license_data or b"COPYRIGHT AND PERMISSION NOTICE" not in license_data:
        raise ValueError("Vendored Unicode license notice is incomplete")
    verify_or_write(table_path, table, outputs["canonicalTsv"], check)
    verify_or_write(cpp_path, render_cpp(records), outputs["cppInclude"], check)
    return stats


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-zip", type=Path, help="Local official Unihan 17.0.0 archive; SHA256 is verified")
    parser.add_argument("--check", action="store_true", help="Verify committed outputs without writing")
    args = parser.parse_args()
    try:
        stats = run(args.source_zip, args.check)
    except (ValueError, OSError, KeyError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1
    print(f"PASS: Unihan {VERSION}, {stats['codepoints']} code points, {stats['readings']} readings; offline deterministic outputs.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
